def build_concept_graph(concepts_data):
    """生成概念图谱（Mermaid mindmap + 关系图）"""
    # 按学科分类
    categories = {}
    for name, data in concepts_data.items():
        meta = CONCEPT_META.get(name, {})
        cat = meta.get("category", "未分类")
        if cat not in categories:
            categories[cat] = []
        categories[cat].append(name)

    # Mindmap
    mindmap = "```mermaid\nmindmap\n  root((知识概念图谱))\n"
    for cat, concepts in sorted(categories.items()):
        mindmap += f"    {cat}\n"
        for c in concepts:
            # 只显示跨2主题以上的概念，标注星数
            tc = concepts_data[c].get("topic_count", 1)
            star = "⭐" * min(tc, 5)
            mindmap += f"      {c}{star}\n"
    mindmap += "```\n"

    # 关系图（核心概念之间的前置/后续关系）
    graph = "```mermaid\ngraph LR\n"
    node_id = 0
    node_map = {}
    for name in concepts_data:
        node_map[name] = f"N{node_id}"
        graph += f'    N{node_id}["{name}"]\n'
        node_id += 1

    for name, data in concepts_data.items():
        meta = CONCEPT_META.get(name, {})
        for pre in meta.get("prerequisites", []):
            if pre in node_map:
                graph += f"    {node_map[pre]} --> {node_map[name]}\n"
    graph += "```\n"

    return mindmap, graph, categories


